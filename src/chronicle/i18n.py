def t(key: str, lang: str = "zh", **kwargs: Any) -> str:
    """取词条并格式化。缺失的 key 原样返回，方便早期开发时发现问题。"""
    table = TEXT.get(lang) or TEXT["zh"]
    template = table.get(key) or TEXT["zh"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template


WEEKDAYS: dict[str, tuple[str, ...]] = {
    "zh": ("周一", "周二", "周三", "周四", "周五", "周六", "周日"),
    "en": ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"),
}


def weekdays(lang: str = "zh") -> tuple[str, ...]:
    return WEEKDAYS.get(lang, WEEKDAYS["zh"])


def chapter_archetypes(lang: str = "zh") -> dict[str, str]:
    return {key: names.get(lang) or names["zh"] for key, names in CHAPTER_ARCHETYPES.items()}
